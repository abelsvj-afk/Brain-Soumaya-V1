/**
 * The Deep Past's real-asset layer — REWORK (2026-10-29, design note
 * `deep-past-rework-design-note.md` §4): a GLB may exist in Deep Past
 * only as a unique, one-time, individual piece — never repeated,
 * instanced, or used as architecture. The manifest therefore keeps
 * exactly four pieces: the First Light basin dish, the anchor spire,
 * the First Light orb (animated), and the supernova remnant in a new
 * hard re-slim. Everything else the old scene loaded — terrace, rim,
 * stair and lantern GLBs, the crystals, and the route-bead GLB — is
 * GONE from the manifest: the strata, rim, and stair are generated in
 * `deepPastScene.ts` from the layout constants, and the route beads
 * are code-built there too (addendum AN15 — the GLB's single gold orb
 * could never show the approved four-light cosmic interior).
 *
 * The loader fetches through the app's shared glTF loader with the
 * honest fallback (null + diagnostics note — the scene degrades,
 * never crashes). Every piece is fitted from its own measured file
 * at load time (span / height / longest side), so a re-slim still
 * lands at the right size; no bare scale factor survives in the load
 * path. All URLs are flat in `public/` (the app's convention) and
 * stay stable across re-slims — same filenames, new contents.
 *
 * SCALE (rework §3): the pre-asset mockup's ×1 proportions, derived
 * from the layout constants (stratum radius 88 − i·3.5, drop 18,
 * basin y −168, radius 66) — every placement below follows them.
 */

export interface DeepPastAssetModel {
  /** Piece key (also the scene holder's name suffix). */
  key: string;
  /** Public URL of the GLB. */
  url: string;
  /** Measured triangles of the shipped file. */
  tris: number;
  /** Measured byte size of the shipped file. */
  bytes: number;
  /** Material count of the file (= draw calls for this piece when loaded as-is). */
  materials: number;
  /** Measured points, for point-cloud models (0 triangles — the
   * supernova remnant is a cloud, not a mesh). Absent means 0. */
  points?: number;
  /** Draw calls when they differ from the material count — a point
   * cloud draws once per mesh, not once per material. Absent means
   * the material count. */
  drawCalls?: number;
}

